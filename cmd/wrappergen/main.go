// endpointFile mirrors the curated endpoint inventory used by contractsync.
type endpointFile struct {
	Endpoints []endpoint `json:"endpoints"`
}

// endpoint contains the contract fields needed to render one wrapper method.
type endpoint struct {
	ID              string   `json:"id"`
	Service         string   `json:"service"`
	MethodName      string   `json:"method_name"`
	Summary         string   `json:"summary"`
	ResponseShape   string   `json:"response_shape"`
	PathParameters  []string `json:"path_parameters"`
	QueryParameters []string `json:"query_parameters"`
	Mutation        bool     `json:"mutation"`
}

// requestSpec binds a contract operation to the stable public request type that callers already use.
type requestSpec struct {
	ID      string
	Request string
	Body    string
	Comment string
}

// fieldInfo records only the type distinction the generator needs when converting request values to strings.
type fieldInfo struct {
	Integer bool
}

